import fs from 'node:fs/promises';
import vm from 'node:vm';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const site=process.argv[2]?path.resolve(process.argv[2]):path.join(root,'dist');
const demo=JSON.parse(await fs.readFile(path.join(site,'demo-data.json'),'utf8'));
const window={confirm:()=>true};
const source=await fs.readFile(path.join(site,'app/web-api.js'),'utf8');
vm.runInNewContext(source,{window,fetch:async()=>({ok:true,json:async()=>demo}),structuredClone,setTimeout,console});
const api=window.api;
let state=await api.getState();
assert.equal(state.testMode,true);
assert.equal(Object.keys(demo.files).length,10);
await api.send({text:demo.meeting,attachments:[],selectedItemId:null});
state=await api.getState();
assert.equal(state.items.length,6);
assert.equal(state.items[0].mappings.length,5);
assert.deepEqual([...new Set(state.items.flatMap(i=>i.mappings.map(m=>m.relation)))].sort(),['중복','보완','신규','충돌','판단 필요'].sort());
assert.equal(state.items[4].status,'confirmed');
assert.equal(state.items[5].status,'excluded');
const isChange=(m)=>!!m.file&&m.relation!=='중복'&&m.relation!=='판단 필요'&&(!!m.moveTo||m.oldText!==m.newText);
const third=state.items[2];
// 판단 필요 파일의 대상을 정하면 그 파일만 채워지고 다른 파일 변경안은 그대로다
const unknown=third.mappings.find(m=>m.relation==='판단 필요');
assert.equal((await api.setMappingFile(third.id,unknown.id,'docs/security/data-retention.md')).ok,true);
const third2=(await api.getState()).items[2];
assert.equal(third2.mappings.find(m=>m.id===unknown.id).relation,'신규');
assert.deepEqual(third2.mappings.filter(m=>m.id!==unknown.id).map(m=>m.newText),third.mappings.filter(m=>m.id!==unknown.id).map(m=>m.newText));
for(const m of third2.mappings.filter(isChange))assert.equal((await api.fileAction(third.id,m.id,'adopt')).ok,true);
assert.equal((await api.getState()).items[2].status,'approved');
assert.equal((await api.applyItems([third.id])).ok,true);
let security=await api.readFile('docs/security/signup-abuse.md');
assert.match(security,/10분에 5회/);
assert.match(security,/마스킹한 이메일/);
assert.match(security,/30일 보관/);
assert.equal((await api.itemAction(third.id,'undo')).ok,true);
assert.equal(await api.readFile('docs/security/signup-abuse.md'),demo.files['docs/security/signup-abuse.md']);
// 파일별 결정: 채택한 파일만 반영하고, 기존 유지·보류한 파일은 그대로 둔다
const first=state.items[0];
const [m0,m1,m2,...rest]=first.mappings;
assert.equal((await api.fileAction(first.id,m0.id,'adopt')).ok,true);
assert.equal((await api.fileAction(first.id,m1.id,'keep')).ok,true);
assert.equal((await api.fileAction(first.id,m2.id,'hold')).ok,true);
assert.equal((await api.getState()).items[0].status,'pending');
for(const m of rest)await api.fileAction(first.id,m.id,'adopt');
assert.equal((await api.getState()).items[0].status,'approved');
assert.equal((await api.applyItems([first.id])).ok,true);
assert.notEqual(await api.readFile(m0.file),demo.files[m0.file]);
assert.equal(await api.readFile(m1.file),demo.files[m1.file]);
assert.equal(await api.readFile(m2.file),demo.files[m2.file]);
assert.equal((await api.itemAction(first.id,'undo')).ok,true);
assert.equal(await api.readFile(m0.file),demo.files[m0.file]);
assert.equal((await api.getState()).items[0].status,'approved');
const second=(await api.getState()).items[1];
for(const m of second.mappings)await api.fileAction(second.id,m.id,'keep');
assert.equal((await api.getState()).items[1].status,'rejected');
await api.fileAction(second.id,second.mappings[0].id,'hold');
assert.equal((await api.getState()).items[1].status,'held');
assert.equal(typeof api.finalize,'undefined');
// 직접 수정 후 제안 채택: 고친 내용까지 반영된다. 채택 뒤에 고치면 채택이 풀린다
const fourth=(await api.getState()).items[3];
const f0=fourth.mappings[0];
await api.fileAction(fourth.id,f0.id,'adopt');
await api.editMapping(fourth.id,f0.id,f0.newText+'\n직접 고친 문장');
assert.equal((await api.getState()).items[3].mappings[0].approvedSig===undefined||(await api.getState()).items[3].status!=='approved',true);
for(const m of fourth.mappings)await api.fileAction(fourth.id,m.id,'adopt');
assert.equal((await api.applyItems([fourth.id])).ok,true);
assert.match(await api.readFile(f0.file),/직접 고친 문장/);
assert.equal((await api.itemAction(fourth.id,'undo')).ok,true);
assert.equal(await api.readFile(f0.file),demo.files[f0.file]);
await api.openDemoProject();
state=await api.getState();
assert.equal(state.items.length,0);
assert.equal(await api.readFile('docs/security/signup-abuse.md'),demo.files['docs/security/signup-abuse.md']);
console.log('Browser test mode: sample, six items, multi-edit apply, all five relations, per-file keep/adopt/hold, undo and reset passed.');
